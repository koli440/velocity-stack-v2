// Usage: node scripts/velodrome-research/apply.mjs [--sample]
// Reads docs/velodrome-research/*.json and regenerates the data migrations, needs-attention.md and rollout-log.md.
// The data is split into many small, independent migrations (<= 20 tracks / ~40 KB each) that call public.apply_velodrome_info():
//  - 20270136010001..: the strict rules (pass 1), chunked by track.
//  - 20270136020001..: only the values newly auto-applied under the relaxed rules (pass 2, PROCESS.md), chunked by track.
//  - 20270136030000: Penrose Park spam-domain strip.
// Old generated chunks are deleted first, so the migration set always equals the current data.
// With --sample it writes the seeded spot-check samples (spot-check-sample.json for the strict run,
// spot-check-relaxed-sample.json for the relaxed delta).
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { BATCHES, evaluate, applyGate, sampleApplied, buildEntries, renderMigration, chunkTracks, withCoordinates } from './lib.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const dir = path.join(root, 'docs/velodrome-research')
const MIGRATIONS = path.join(root, 'supabase/migrations')
const STRICT_BASE = 20270136010000
const RELAXED_BASE = 20270136020000
const PENROSE_VERSION = '20270136030000'
const GENERATED_RE = /^(2027013601\d{4}_velodrome_info_strict_\d+|2027013602\d{4}_velodrome_info_relaxed_\d+|20270136030000_velodrome_penrose_notes)\.sql$/
const SEED = 'velodrome-research-2026-11-05'
const read = (f) => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'))

const inputs = BATCHES.map((b) => ({
  batch: b,
  research: read(`${b}.json`),
  review: read(b === 'pilot' ? 'pilot-review.json' : `${b}-review.json`),
}))
const strict = evaluate(inputs, 'strict')
const { items, notFound, corrections } = evaluate(inputs, 'relaxed')

const resultsFile = path.join(dir, 'spot-check.json')
const results = fs.existsSync(resultsFile) ? read('spot-check.json').results : []
const gate = applyGate(strict.items, results)
applyGate(items, results)

// Items are index-aligned between the two runs. Delta = applied only under the relaxed rules.
const strictApplied = strict.items.filter((i) => i.decision === 'apply')
const delta = items.filter((it, idx) => it.decision === 'apply' && strict.items[idx].decision !== 'apply')
const regressed = items.filter((it, idx) => strict.items[idx].decision === 'apply' && it.decision !== 'apply')
const relaxedFile = path.join(dir, 'spot-check-relaxed.json')
const relaxedResults = fs.existsSync(relaxedFile) ? read('spot-check-relaxed.json').results : []
const gateRelaxed = applyGate(delta, relaxedResults)

const applied = items.filter((i) => i.decision === 'apply')
if (process.argv.includes('--sample')) {
  const flat = (sample) => Object.entries(sample).flatMap(([batch, arr]) =>
    arr.map((i) => ({ batch, name: i.name, field: i.field, value: i.value_text, url: i.review?.source_url_fix || i.source_url, quote: i.evidence, relax: i.relax })))
  const old = flat(sampleApplied(strictApplied, SEED)).map(({ relax, ...rest }) => rest)
  fs.writeFileSync(path.join(dir, 'spot-check-sample.json'), JSON.stringify({ seed: SEED, sample: old }, null, 1) + '\n')
  // Relaxed values are riskier: at least 20% of each batch's newly applied values, minimum 5 per batch.
  const rel = flat(sampleApplied(delta.map((i) => ({ ...i })), `${SEED}|relaxed`, { rate: 0.2, min: 5 }))
  fs.writeFileSync(path.join(dir, 'spot-check-relaxed-sample.json'), JSON.stringify({ seed: `${SEED}|relaxed`, sample: rel }, null, 1) + '\n')
  console.log(`sample: ${old.length} of ${strictApplied.length}; relaxed sample: ${rel.length} of ${delta.length}`)
}

const coords = read('track-coordinates.json')
const pad = (n) => String(n).padStart(2, '0')
for (const f of fs.readdirSync(MIGRATIONS)) if (GENERATED_RE.test(f)) fs.rmSync(path.join(MIGRATIONS, f))
const migrationFiles = []
function writeChunks(pass, base, tracks, headerText) {
  chunkTracks(withCoordinates(tracks, coords)).forEach((chunk, idx) => {
    const batch = `${pass}-${pad(idx + 1)}`
    const header = `-- Velodrome info data ${pass} ${pad(idx + 1)} (docs/velodrome-research). GENERATED by scripts/velodrome-research/apply.mjs; do not edit by hand.
${headerText}`
    const file = `${base + idx + 1}_velodrome_info_${pass}_${pad(idx + 1)}.sql`
    fs.writeFileSync(path.join(MIGRATIONS, file), renderMigration(chunk, header, batch))
    migrationFiles.push({ file, tracks: chunk.length })
  })
}

writeChunks('strict', STRICT_BASE, buildEntries(strict.items, strict.notFound), `-- Pass 1 (strict rules): verified, reviewer-confirmed values from official sources only. Fill-only: existing values are
-- never overwritten. Tolerant: an unmatched/ambiguous track or a rejected field is skipped and logged to
-- public.track_info_apply_log; this migration cannot fail. Independent of every other data migration.
`)

const deltaEntries = buildEntries(delta.filter((i) => i.decision === 'apply'), [])
writeChunks('relaxed', RELAXED_BASE, deltaEntries, `-- Pass 2 (relaxed auto-apply rules in PROCESS.md): only values newly allowed by the relaxed rules (reviewer-verified medium
-- confidence, operator/owner pages without a source_kind, value-stated scope caveats). Fill-only and idempotent; a differing
-- existing value is recorded as needs_attention. Staff/personal/council contacts remain excluded. Tolerant like pass 1.
`)

// Safety exception: the Penrose Park seed notes carried penroseparkvelo.com, a hijacked spam domain; it is stripped.
const penrose = `-- Safety: the Penrose Park Velodrome seed notes carried penroseparkvelo.com, a hijacked spam domain; strip it (keeps the rest).
-- GENERATED by scripts/velodrome-research/apply.mjs; do not edit by hand. Idempotent; cannot fail the migration.
DO $migration$
BEGIN
    UPDATE public.tracks
    SET notes = NULLIF(btrim(regexp_replace(notes, 'https?://(www\\.)?penroseparkvelo\\.com/?', '', 'gi'), E' \\n\\t'), '')
    WHERE name ILIKE '%penrose%' AND notes ~* 'penroseparkvelo\\.com';
EXCEPTION WHEN OTHERS THEN
    RAISE NOTICE 'velodrome penrose notes: skipped (%): %', SQLSTATE, SQLERRM;
END
$migration$;
`
fs.writeFileSync(path.join(MIGRATIONS, `${PENROSE_VERSION}_velodrome_penrose_notes.sql`), penrose)

// ---- reports ----
const count = (arr, f) => arr.reduce((m, x) => ((m[f(x)] = (m[f(x)] || 0) + 1), m), {})
const deltaApplied = delta.filter((i) => i.decision === 'apply')
let log = `# Rollout log\n\nGenerated by \`scripts/velodrome-research/apply.mjs\` (seed \`${SEED}\`).\n\n`
log += `## Pass 1 (strict rules, migrations 20270136010001+) vs pass 2 (relaxed rules, migrations 20270136020001+)\n\n`
log += `Pass 1 applied ${strictApplied.length} values. Pass 2 adds ${deltaApplied.length} newly allowed values (${delta.length - deltaApplied.length} more were excluded by the relaxed-value spot-check); ${regressed.length} pass-1 values are now flagged as conflicting with another verified source (they stay in the database, fill-only, and are listed in needs-attention).\n\n`
log += `| Field | Before (strict) | Added (relaxed) | After |\n|---|---|---|---|\n`
const fields = [...new Set([...strictApplied, ...deltaApplied].map((i) => i.field))].sort()
for (const f of fields) {
  const b4 = strictApplied.filter((i) => i.field === f).length
  const add = deltaApplied.filter((i) => i.field === f).length
  log += `| ${f} | ${b4} | ${add} | ${b4 + add} |\n`
}
log += `| **Total** | ${strictApplied.length} | ${deltaApplied.length} | ${strictApplied.length + deltaApplied.length} |\n\n`
log += `Newly applied by relaxation used: `
const relaxCounts = count(deltaApplied.flatMap((i) => i.relax || []), (x) => x)
log += Object.entries(relaxCounts).map(([k, v]) => `${k === 'medium' ? 'confidence medium' : 'source_kind reclassified'}: ${v}`).join(', ') + `. Opening hours/price values carrying a stated scope or caveat: ${deltaApplied.filter((i) => ['opening_hours', 'price_range'].includes(i.field)).length}.\n\n`
log += `## Source-kind reclassifications (null/other -> operator/owner)\n\nEach applied value whose source_kind was missing (pilot) or "other" and was classified by domain/page (see \`OFFICIAL_PAGE_RECLASS\` in lib.mjs):\n\n| Track | Field | From | To | Page | Why |\n|---|---|---|---|---|---|\n`
for (const i of deltaApplied.filter((x) => x.reclassified)) {
  log += `| ${i.name} (${i.country_code}) | ${i.field} | ${i.reclassified.from ?? 'null'} | ${i.reclassified.to} | ${i.source_url} | ${i.reclassified.why} |\n`
}
log += `\n## Per-batch counts (after pass 2)\n\n| Batch | Candidates | Auto-applied | of which pass 2 | Held back | Excluded (rejected/unverifiable) | Duplicates |\n|---|---|---|---|---|---|---|\n`
const totals = { c: 0, a: 0, p2: 0, h: 0, e: 0, d: 0, s: 0, f: 0 }
for (const b of BATCHES) {
  const it = items.filter((i) => i.batch === b)
  const n = (d) => it.filter((i) => i.decision === d).length
  const p2 = deltaApplied.filter((i) => i.batch === b).length
  log += `| ${b} | ${it.length} | ${n('apply')} | ${p2} | ${n('hold')} | ${n('exclude')} | ${n('duplicate')} |\n`
  totals.c += it.length; totals.a += n('apply'); totals.p2 += p2; totals.h += n('hold'); totals.e += n('exclude'); totals.d += n('duplicate')
}
log += `| **Total** | ${totals.c} | ${totals.a} | ${totals.p2} | ${totals.h} | ${totals.e} | ${totals.d} |\n\n`
log += `## Auto-applied by field (after pass 2)\n\n| Field | Count |\n|---|---|\n`
for (const [f, c] of Object.entries(count(applied, (i) => i.field)).sort()) log += `| ${f} | ${c} |\n`
log += `\n## Held back / excluded by reason (per batch, after pass 2)\n\n| Batch | Reason code | Count |\n|---|---|---|\n`
for (const b of BATCHES) {
  const it = items.filter((i) => i.batch === b && !['apply', 'duplicate'].includes(i.decision))
  for (const [code, c] of Object.entries(count(it, (i) => i.code)).sort()) log += `| ${b} | ${code} | ${c} |\n`
}
log += `\n## Not found\n\n${notFound.length} fields were checked without an official source and recorded as \`not_found\` (migration skips fields that have a candidate and identity-held tracks).\n`
log += `\n## Quality gate\n\n`
log += `### Pass 1 (strict)\n\n${results.length ? '' : '_No spot-check results recorded yet._\n'}Sample: ~10% of auto-applied values per batch (min 3), seeded sampling. A batch with more than 5% sampled failures is removed entirely.\n\n`
for (const [b, g] of Object.entries(gate.perBatch)) {
  log += `- ${b}: ${g.sampled} sampled, ${g.failed} failed${gate.halted.includes(b) ? ' — **BATCH HALTED, nothing applied**' : ''}\n`
  for (const f of g.failures) log += `  - FAIL ${f.name} / ${f.field}: ${f.note || ''}\n`
}
log += `\n### Pass 2 (relaxed values)\n\n${relaxedResults.length ? '' : '_No spot-check results recorded yet._\n'}Sample: at least 20% of each batch's newly relaxed values (min 5 per batch), seeded, fresh independent re-fetch. Same halt rule (>5% failures removes the batch's pass-2 values); failed values are always excluded.\n\n`
log += `| Batch | Newly applied (before gate) | Sampled | Failed | Failure rate |\n|---|---|---|---|---|\n`
let rs = 0, rf = 0
for (const b of BATCHES) {
  const g = gateRelaxed.perBatch[b]
  const n = delta.filter((i) => i.batch === b).length
  if (!n) continue
  const sampled = g?.sampled || 0, failed = g?.failed || 0
  rs += sampled; rf += failed
  log += `| ${b} | ${n} | ${sampled} | ${failed} | ${sampled ? ((100 * failed) / sampled).toFixed(0) : 0}% |\n`
}
log += `| **Total** | ${delta.length} | ${rs} | ${rf} | ${rs ? ((100 * rf) / rs).toFixed(1) : 0}% |\n\n`
for (const [b, g] of Object.entries(gateRelaxed.perBatch)) {
  if (gateRelaxed.halted.includes(b)) log += `- ${b}: **BATCH HALTED, no pass-2 values applied**\n`
  for (const f of g.failures) log += `- FAIL ${b}: ${f.name} / ${f.field}: ${f.note || ''}\n`
}
if (regressed.length) {
  log += `\n### Pass-1 values now in conflict\n\n`
  for (const i of regressed) log += `- ${i.name} / ${i.field} (${i.batch}): ${i.reason}\n`
}
fs.writeFileSync(path.join(dir, 'rollout-log.md'), log)

let na = `# Needs attention\n\nValues that were not auto-applied and need a human or a further research pass. Rejected and unverifiable values never reach the database.\n\n`
const byTrack = new Map()
for (const i of items.filter((x) => ['hold', 'exclude'].includes(x.decision))) {
  const k = `${i.name} (${i.country_code})`
  if (!byTrack.has(k)) byTrack.set(k, [])
  byTrack.get(k).push(i)
}
for (const c of corrections) {
  const k = `${c.name} (${c.country_code})`
  if (!byTrack.has(k)) byTrack.set(k, [])
  byTrack.get(k).push({ field: c.field, value_text: JSON.stringify(c.proposed), code: 'correction', decision: 'hold', reason: `Proposed correction to the seed (never auto-applied; reviewer verdict ${c.verdict}): ${c.reason}`, source_url: c.source_url })
}
for (const k of [...byTrack.keys()].sort()) {
  na += `## ${k}\n\n`
  for (const i of byTrack.get(k)) {
    const url = i.review?.source_url_fix || i.source_url
    na += `- **${i.field}** = \`${String(i.value_text ?? '').replace(/\n/g, ' ')}\` — ${i.decision === 'exclude' ? 'excluded' : 'held'} [${i.code}]: ${String(i.reason).replace(/\n/g, ' ')}${url ? ` (${url})` : ''}\n`
  }
  na += '\n'
}
fs.writeFileSync(path.join(dir, 'needs-attention.md'), na)
console.log(migrationFiles.map((m) => `${m.file} (${m.tracks} tracks)`).join('\n'))
console.log(JSON.stringify({ ...totals, strict: strictApplied.length, delta: delta.length, regressed: regressed.length }))
